#!/usr/bin/env python3
"""ENGINE tool: build src/videos/<id>/timeline.ts from the real voice (identity timeline, no warp).
usage: python3 timeline.py <script.txt> <words.json> <voice.wav> <out timeline.ts>
  script.txt : the narration with [shotname] markers before the first word of each beat, e.g.
               [hook] He put a little clock on a sidewalk, [war] and the whole city declared war on it.
  words.json : Whisper word timings [{"w": "He", "s": 0.0, "e": 0.24}, ...]  (or [[w, s, e], ...])
  voice.wav  : the loudnorm'ed voice (duration = END_REAL / VOICE_END)
Captions (CAPS): 1-3 words, break after punctuation or a pause > 0.25 s (Ricks Clips: hard swaps)."""
import json, re, sys, subprocess, difflib
scr, wj, wav, out = sys.argv[1:5]
norm = lambda s: re.sub(r"[^a-z0-9']", '', s.lower())
W = json.load(open(wj)); W = [(x['w'], x['s'], x['e']) if isinstance(x, dict) else tuple(x) for x in W]
W = [(w.strip(), round(s, 3), round(e, 3)) for w, s, e in W if w.strip()]
toks, marks = [], {}
for t in open(scr).read().split():
    m = re.fullmatch(r'\[(\w+)\]', t)
    if m: marks[len(toks)] = m.group(1)
    else: toks.append(t)
a, b = [norm(t) for t in toks], [norm(w[0]) for w in W]
sm = difflib.SequenceMatcher(a=a, b=b, autojunk=False); idx = {}
for blk in sm.get_matching_blocks():
    for k in range(blk.size): idx[blk.a + k] = blk.b + k
def wordOf(i):   # script token i -> whisper word index (nearest matched after)
    for j in range(i, len(toks)):
        if j in idx: return idx[j]
    return len(W) - 1
dur = float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', wav]).decode())
shot_real = {}
for i, name in sorted(marks.items()):
    shot_real[name] = 0.0 if not shot_real else W[wordOf(i)][1]
first = min(shot_real.values()) if shot_real else 0
caps, i = [], 0
while i < len(W):
    j = i
    while j + 1 < len(W) and j - i < 2 and not re.search(r'[,.?!;:]$', W[j][0]) and W[j + 1][1] - W[j][2] <= 0.25: j += 1
    caps.append([i, j]); i = j + 1
J = lambda o: json.dumps(o)
words = [[w, s, e] for w, s, e in W]
src = f'''// GENERATED by engine/tools/timeline.py from the real voice (identity timeline: staging clock = voice clock)
export const FPS = 30;
export const OLD_TOTAL = {round(dur * 30)};
export const WORDS: [string, number, number][] = {J(words)};
export const CAPS: [number, number][] = {J(caps)};
export const SHOT_START: Record<string, number> = {J({k: round(v * 30) for k, v in shot_real.items()})};
export const SHOT_REAL: Record<string, number> = {J(shot_real)};
export const WORDS_REAL: [string, number, number][] = {J(words)};
export const END_REAL = {dur:.2f};
export const VOICE_END = {dur:.3f};
export const WARP: [number, number][] = [[0, 0], [{dur:.3f}, {dur:.3f}]];
export const warp = (t: number) => t;
'''
open(out, 'w').write(src); print('shots', len(shot_real), 'words', len(W), 'caps', len(caps), 'dur', round(dur, 2))
